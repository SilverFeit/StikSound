import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import {
  StikSoundError,
  isVideoFormat,
  type PcmMono48k,
  type VideoRenderRequest,
  type VideoRenderResult
} from "@stiksound/core";
import { encodeWavBytes, sniffImageHeader } from "@stiksound/media-web";
import { padPcmToDuration } from "./audio";
import {
  ProcessFailedError,
  detectCapabilities,
  pickH264Encoder,
  pickOpusEncoder,
  runBinary,
  type FfmpegBinaries
} from "./ffmpeg";
import { probeVideoClip, squareCropFilter } from "./image";
import { probeFile } from "./probe";
import { withTempDir } from "./temp";

/**
 * Output frame rates. ffmpeg ends a file on a whole frame, so the picture track can run up to one
 * frame past the requested length. Both rates keep that under the 50 ms duration tolerance the
 * export use case enforces (40 ms and 41.7 ms).
 */
const STILL_FPS = 25;
const MOTION_FPS = 24;

export type StickerMotion = "still" | "gif" | "clip";

export interface VideoArgsInput {
  motion: StickerMotion;
  stickerPath: string;
  audioPath: string;
  outputPath: string;
  sourceWidth: number;
  sourceHeight: number;
  cropX: number;
  cropY: number;
  /** Clips only: where in the clip the rendered segment starts. */
  clipOffsetMs: number;
  durationMs: number;
  matteColor: string;
  container: "mp4" | "webm-alpha";
  videoEncoder: string;
  audioEncoder: string;
}

/** `#RRGGBB` to the `0xRRGGBB` form ffmpeg's color source takes. Anything else is rejected. */
export function matteToFfmpegColor(raw: string): string {
  const trimmed = raw.trim();
  if (!/^#[0-9a-fA-F]{6}$/.test(trimmed)) {
    throw new StikSoundError("encode-failed", `Invalid matte color: ${raw}`);
  }
  return `0x${trimmed.slice(1).toUpperCase()}`;
}

function h264Args(encoder: string, motion: StickerMotion): string[] {
  if (encoder === "libx264") {
    const tune = motion === "still" ? ["-tune", "stillimage"] : [];
    return ["-c:v", "libx264", "-preset", "medium", "-crf", "20", "-profile:v", "high", ...tune];
  }
  // Hardware and OpenH264 encoders have no CRF mode; a fixed bitrate is plenty for 512 px.
  return ["-c:v", encoder, "-b:v", "1500k"];
}

/**
 * Builds the complete ffmpeg argument list for one render. Every value is a separate argument and
 * the only free-form inputs (paths, color) are validated or generated by the caller, so nothing
 * here is ever interpreted by a shell.
 */
export function buildVideoArgs(input: VideoArgsInput): string[] {
  const fps = input.motion === "still" ? STILL_FPS : MOTION_FPS;
  const seconds = (input.durationMs / 1000).toFixed(3);
  const { filter: cropFilter, outputSize } = squareCropFilter(
    input.sourceWidth,
    input.sourceHeight,
    input.cropX,
    input.cropY
  );

  const stickerInput =
    input.motion === "still"
      ? ["-loop", "1", "-framerate", String(STILL_FPS), "-noautorotate", "-i", input.stickerPath]
      : ["-stream_loop", "-1", "-i", input.stickerPath];

  // Short GIFs and clips loop for the whole segment; a clip starts at its offset and wraps around.
  const chain: string[] = [];
  if (input.motion === "clip" && input.clipOffsetMs > 0) {
    chain.push(`trim=start=${(input.clipOffsetMs / 1000).toFixed(3)}`, "setpts=PTS-STARTPTS");
  }
  if (input.motion !== "still") {
    chain.push(`fps=${fps}`);
  }
  chain.push(cropFilter, "format=rgba");

  let filterComplex: string;
  let codecArgs: string[];
  if (input.container === "mp4") {
    const matte = matteToFfmpegColor(input.matteColor);
    filterComplex =
      `color=c=${matte}:s=${outputSize}x${outputSize}:r=${fps}[bg];` +
      `[0:v]${chain.join(",")}[fg];` +
      `[bg][fg]overlay=format=auto,format=yuv420p[v]`;
    codecArgs = [
      ...h264Args(input.videoEncoder, input.motion),
      "-pix_fmt", "yuv420p",
      "-c:a", "aac", "-b:a", "128k", "-ar", "48000", "-ac", "1",
      "-movflags", "+faststart"
    ];
  } else {
    filterComplex = `[0:v]${chain.join(",")},format=yuva420p[v]`;
    const experimental = input.audioEncoder === "opus" ? ["-strict", "-2"] : [];
    codecArgs = [
      "-c:v", input.videoEncoder, "-pix_fmt", "yuva420p", "-auto-alt-ref", "0", "-crf", "30", "-b:v", "0",
      "-c:a", input.audioEncoder, ...experimental, "-b:a", "64k", "-ar", "48000", "-ac", "1"
    ];
  }

  return [
    "-v", "error", "-y",
    ...stickerInput,
    "-i", input.audioPath,
    "-filter_complex", filterComplex,
    "-map", "[v]", "-map", "1:a:0",
    "-r", String(fps),
    ...codecArgs,
    "-t", seconds,
    input.outputPath
  ];
}

/** Length of the picture track of a rendered file, falling back to the container duration. */
async function measureDurationMs(binaries: FfmpegBinaries, filePath: string): Promise<number> {
  const probed = await probeFile(binaries, filePath);
  const video = probed.streams.find((stream) => stream.codecType === "video");
  return video?.durationMs || probed.durationMs;
}

/**
 * Renders the square sticker video: the picture (still, looping GIF or clip segment) over a matte
 * for MP4 or with its alpha for WebM, plus the already trimmed audio padded to the full length.
 */
export async function renderStickerVideo(
  binaries: FfmpegBinaries,
  request: VideoRenderRequest,
  audio: PcmMono48k
): Promise<VideoRenderResult> {
  const audioWindowMs = request.endMs - request.startMs;
  const durationMs = Math.max(audioWindowMs, Math.round(request.minDurationMs ?? 0));

  const capabilities = await detectCapabilities(binaries.ffmpeg);
  const isMp4 = request.container === "mp4";
  const videoEncoder = isMp4
    ? pickH264Encoder(capabilities.encoders)
    : capabilities.encoders.has("libvpx-vp9")
      ? "libvpx-vp9"
      : null;
  if (!videoEncoder) {
    throw new StikSoundError(
      "unsupported-codec",
      isMp4 ? "This FFmpeg build has no H.264 encoder." : "This FFmpeg build has no libvpx-vp9 encoder for WebM with alpha."
    );
  }
  const audioEncoder = isMp4 ? "aac" : pickOpusEncoder(capabilities.encoders);
  if (!audioEncoder) {
    throw new StikSoundError("unsupported-codec", "This FFmpeg build has no Opus encoder.");
  }

  const isClip = isVideoFormat(request.stickerFormat);
  // Only GIFs animate; any other image contributes its first frame, matching the web engine.
  const motion: StickerMotion = isClip ? "clip" : request.stickerFormat === "gif" && request.animated ? "gif" : "still";

  return withTempDir(async (dir) => {
    const stickerPath = path.join(dir, `sticker.${request.stickerFormat}`);
    const audioPath = path.join(dir, "audio.wav");
    const outputPath = path.join(dir, isMp4 ? "out.mp4" : "out.webm");
    await writeFile(stickerPath, request.stickerBytes);
    await writeFile(audioPath, encodeWavBytes(padPcmToDuration(audio, durationMs)));

    let size: { width: number; height: number };
    if (!isClip) {
      size = sniffImageHeader(request.stickerBytes);
    } else if (request.stickerWidth && request.stickerHeight) {
      size = { width: request.stickerWidth, height: request.stickerHeight };
    } else {
      size = await probeVideoClip(binaries, stickerPath);
    }

    const args = buildVideoArgs({
      motion,
      stickerPath,
      audioPath,
      outputPath,
      sourceWidth: size.width,
      sourceHeight: size.height,
      cropX: request.cropX ?? 0.5,
      cropY: request.cropY ?? 0.5,
      clipOffsetMs: isClip ? Math.max(0, Math.round(request.videoOffsetMs ?? 0)) : 0,
      durationMs,
      matteColor: request.matteColor,
      container: request.container,
      videoEncoder,
      audioEncoder
    });

    try {
      await runBinary(binaries.ffmpeg, args, { timeoutMs: 180_000 });
    } catch (err) {
      if (err instanceof ProcessFailedError) {
        throw new StikSoundError("encode-failed", `FFmpeg could not render the video: ${err.message}`);
      }
      throw err;
    }

    const bytes = new Uint8Array(await readFile(outputPath));
    return {
      bytes,
      mimeType: isMp4 ? "video/mp4" : "video/webm",
      extension: isMp4 ? "mp4" : "webm",
      durationMs: await measureDurationMs(binaries, outputPath),
      hasAlpha: !isMp4
    };
  });
}
